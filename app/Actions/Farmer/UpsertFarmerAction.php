        ?bool $areYouTheHeadOfTheFamily = null,
        ?string $ifNoHighestEducationalAttainmentOfHeadOfFamily = null,
        ?string $challengesOrProblemsEncounteredInDairyFarming = null,
        IncomeSourceEnum|string|null $mainSourceOfIncome = null,
        ?float $mainAnnualNetIncome = null,
        IncomeSourceEnum|string|null $secondarySourceOfIncome = null,
        ?float $secondaryAnnualNetIncome = null,
        IncomeSourceEnum|string|null $tertiarySourceOfIncome = null,
        ?float $tertiaryAnnualNetIncome = null,
        IncomeSourceEnum|string|null $quaternarySourceOfIncome = null,
        ?float $quaternaryAnnualNetIncome = null,
        ?float $avgNetIncome = null,
        ?int $staffCountMale = null,
        ?int $staffCountFemale = null,
        ?float $aveMonthlySalary = null,
        ?string $statusGoogleMap = null,
        ?string $googleMapLink = null,
        ?float $gpsLatitude = null,
        ?float $gpsLongitude = null,
        ?string $geotagImage = null,
        ManagementSystemEnum|string|null $managementSystem = null,
        ?bool $isDrylot = null,
        ?int $durationOfStocking = null,
        ?bool $isAppliedInTheField = null,
        ?bool $isDryRiceField = null,
        ?bool $isDryVegetable = null,
        ?bool $isVermicomposting = null,
        ?bool $isPastureRangePaddock = null,
        ?bool $isDailySpread = null,
        ?bool $isStorageBulking = null,
        ?bool $isLiquidSlurry = null,
        ?bool $isAnaerobicDigester = null,
        ?string $foragesRainyAndDry = null,
        ?string $silageSpecification = null,
