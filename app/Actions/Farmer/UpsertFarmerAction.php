    private function calculateTotalNetIncome(
        ?float $main,
        ?float $secondary,
        ?float $tertiary,
        ?float $quaternary
    ): ?float {
        $total = 0.0;
        if ($main !== null) {
            $total += $main;
        }
        if ($secondary !== null) {
            $total += $secondary;
        }
        if ($tertiary !== null) {
            $total += $tertiary;
        }
        if ($quaternary !== null) {
            $total += $quaternary;
        }

        return $total > 0 ? $total : null;
    }
}
