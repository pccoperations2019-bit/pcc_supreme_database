            [
                'code' => $farmerCode,
                'center_id' => $centerId,
            ],
            array_filter([
                'center_id' => $centerId,
                'partner_id' => $partnerId,
                'date_of_interview' => $dateOfInterview,
                'date_of_enrollment' => $dateOfEnrollment,
                'category' => $category,
                'status' => $status,
                'category_size' => $categorySize,
                'birthday' => $dateOfBirth,
                'photo' => $photo,
                'first_name' => $firstName,
                'last_name' => $lastName,
                'middle_name' => $middleName,
