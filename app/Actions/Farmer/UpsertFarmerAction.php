                'staff_count_male' => $staffCountMale,
                'staff_count_female' => $staffCountFemale,
                'ave_monthly_salary' => $aveMonthlySalary,
                'status_google_map' => $statusGoogleMap,
                'google_map_link' => $googleMapLink,
                'gps_latitude' => $gpsLatitude,
                'gps_longitude' => $gpsLongitude,
                'geotag_image' => $geotagImage,
                'management_system' => $managementSystem,
                'is_drylot' => $isDrylot,
                'duration_of_stocking' => $durationOfStocking,
                'is_applied_in_the_field' => $isAppliedInTheField,
                'is_dry_rice_field' => $isDryRiceField,
                'is_dry_vegetable' => $isDryVegetable,
                'is_vermicomposting' => $isVermicomposting,
                'is_pasture_range_paddock' => $isPastureRangePaddock,
                'is_daily_spread' => $isDailySpread,
                'is_storage_bulking' => $isStorageBulking,
                'is_liquid_slurry' => $isLiquidSlurry,
                'is_anaerobic_digester' => $isAnaerobicDigester,
